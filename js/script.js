// FUNCIÓN PARA CAMBIAR EL IDIOMA
function cambiarIdioma(idioma) {

    if (!traducciones[idioma]) {
        return;
    }

    const elementos = document.querySelectorAll("[data-i18n]");

    elementos.forEach(elemento => {
        const clave = elemento.dataset.i18n;

        if (traducciones[idioma][clave]) {
            elemento.textContent = traducciones[idioma][clave];
        }
    });

    document.documentElement.lang = idioma;

    localStorage.setItem("idioma", idioma);
}


// BOTONES DE IDIOMA
document.getElementById("lang-gl")?.addEventListener("click", () => {
    cambiarIdioma("gl");
});

document.getElementById("lang-es")?.addEventListener("click", () => {
    cambiarIdioma("es");
});


// RECUPERAR IDIOMA GUARDADO
const idiomaGuardado = localStorage.getItem("idioma") || "gl";

cambiarIdioma(idiomaGuardado);
